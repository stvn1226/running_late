using UnityEngine;

public class PowerUpContract
{
    /// <summary>
    /// The name of the power-up.
    /// </summary>
    public string powerUpName;
    /// <summary>
    /// The duration of the power-up effect in seconds.
    /// </summary>
    public float duration;
    /// <summary>
    /// The image representing the power-up.
    /// </summary>
    public Sprite image;
    /// <summary>
    /// The color associated with the power-up.
    /// </summary>
    public Color color;
}
