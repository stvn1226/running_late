#!/bin/bash
awk '
BEGIN { in_func = 0; }
/private static void Pass3_GenerateSidewalk/ {
    in_func = 1;
    print "    private static void Pass3_GenerateSidewalk(LevelBlueprint blueprint, ModuleBuilder[] sidewalkModules, ModuleBuilder slopeLeftModule, ModuleBuilder slopeRightModule, ModuleBuilder diagUp, ModuleBuilder diagDown, int safeZoneModules, int sidewalkMaxRelHeight, bool logDualLayer)"
    print "    {"
    print "        if (blueprint.RoadTrack == null || blueprint.RoadTrack.Segments == null || blueprint.RoadTrack.Segments.Count == 0) return;"
    print ""
    print "        float singleSpace = sidewalkModules != null && sidewalkModules.Length > 0 ? sidewalkModules[0].moduleConfig.currentTerrainWidth : 15f;"
    print "        float startRampWidth = diagUp != null ? diagUp.moduleConfig.currentTerrainWidth : singleSpace;"
    print "        float endRampWidth = diagDown != null ? diagDown.moduleConfig.currentTerrainWidth : singleSpace;"
    print ""
    print "        // FIND THE FIRST UPWARD ROAD SLOPE"
    print "        float startRampX = -1f;"
    print "        float endRampX = -1f;"
    print "        float sidewalkStartX = -1f;"
    print "        float sidewalkEndX = -1f;"
    print "        int roadElevAtStart = 0;"
    print "        int roadElevAtEnd = 0;"
    print ""
    print "        // Find start ramp (first upward slope)"
    print "        foreach (var rSeg in blueprint.RoadTrack.Segments) {"
    print "            if (rSeg.IsSlope && rSeg.Y_Elevation > 0) {"
    print "                startRampX = rSeg.X_Position;"
    print "                sidewalkStartX = startRampX + startRampWidth;"
    print "                roadElevAtStart = rSeg.Y_Elevation - 1; // Elevation before slope"
    print "                break;"
    print "            }"
    print "        }"
    print ""
    print "        // Find end ramp (last downward slope)"
    print "        for (int i = blueprint.RoadTrack.Segments.Count - 1; i >= 0; i--) {"
    print "            var rSeg = blueprint.RoadTrack.Segments[i];"
    print "            if (rSeg.IsSlope && rSeg.Y_Elevation == 0) { // Going down to baseline"
    print "                endRampX = rSeg.X_Position;"
    print "                sidewalkEndX = rSeg.X_Position;"
    print "                roadElevAtEnd = 0; // Elevation after slope"
    print "                break;"
    print "            }"
    print "        }"
    print ""
    print "        // Fallbacks if no slopes exist"
    print "        if (startRampX == -1f) {"
    print "            startRampX = blueprint.HouseAnchor.X_Position + blueprint.HouseAnchor.Width + singleSpace;"
    print "            sidewalkStartX = startRampX + startRampWidth;"
    print "        }"
    print "        if (endRampX == -1f) {"
    print "            endRampX = blueprint.SchoolAnchor.X_Position - singleSpace - endRampWidth;"
    print "            sidewalkEndX = endRampX;"
    print "        }"
    print ""
    print "        // GENERATE DIAGONAL RAMPS"
    print "        if (diagUp != null) {"
    print "            blueprint.DiagonalRamps.Add(new SegmentData {"
    print "                Template = diagUp,"
    print "                X_Position = startRampX,"
    print "                Y_Elevation = roadElevAtStart,"
    print "                Width = startRampWidth,"
    print "                Label = \"Diagonal_Ramp_Start\","
    print "                IsSlope = false,"
    print "                SpawnObstacles = false,"
    print "                RoadElevationAtX = roadElevAtStart,"
    print "                SidewalkRelativeLevel = 0,"
    print "                ConnectorRoadElevation = roadElevAtStart,"
    print "                ConnectorRelLevelFrom = 0,"
    print "                ConnectorRelLevelTo = 1"
    print "            });"
    print "        }"
    print ""
    print "        if (diagDown != null) {"
    print "            blueprint.DiagonalRamps.Add(new SegmentData {"
    print "                Template = diagDown,"
    print "                X_Position = endRampX,"
    print "                Y_Elevation = roadElevAtEnd,"
    print "                Width = endRampWidth,"
    print "                Label = \"Diagonal_Ramp_End\","
    print "                IsSlope = false,"
    print "                SpawnObstacles = false,"
    print "                RoadElevationAtX = roadElevAtEnd,"
    print "                SidewalkRelativeLevel = 0,"
    print "                ConnectorRoadElevation = roadElevAtEnd,"
    print "                ConnectorRelLevelFrom = 1,"
    print "                ConnectorRelLevelTo = 0"
    print "            });"
    print "        }"
    print ""
    print "        // GENERATE SIDEWALK SEGMENTS"
    print "        float currentX = sidewalkStartX;"
    print "        while (currentX < sidewalkEndX) {"
    print "            float segX = currentX;"
    print "            // Find corresponding road segment to copy height"
    print "            SegmentData matchingRoadSeg = null;"
    print "            foreach (var rSeg in blueprint.RoadTrack.Segments) {"
    print "                if (segX >= rSeg.X_Position && segX < rSeg.X_Position + rSeg.Width) {"
    print "                    matchingRoadSeg = rSeg;"
    print "                    break;"
    print "                }"
    print "            }"
    print ""
    print "            if (matchingRoadSeg == null) {"
    print "                currentX += singleSpace;"
    print "                continue;"
    print "            }"
    print ""
    print "            // Ensure sidewalk width matches road segment remaining width"
    print "            float remainingRoadWidth = (matchingRoadSeg.X_Position + matchingRoadSeg.Width) - segX;"
    print "            float segWidth = Mathf.Min(remainingRoadWidth, singleSpace);"
    print "            if (segWidth < 1f) segWidth = singleSpace; // Fallback"
    print ""
    print "            ModuleBuilder template = null;"
    print "            bool isSlope = matchingRoadSeg.IsSlope;"
    print ""
    print "            // Do NOT generate Sidewalk on the exact spots where the Diagonal Ramps are!"
    print "            // Actually, sidewalkStartX is after startRampX, so it naturally skips startRamp."
    print "            // And sidewalkEndX is at endRampX, so it stops before endRamp."
    print ""
    print "            if (isSlope) {"
    print "                bool isUp = matchingRoadSeg.Y_Elevation > 0 && matchingRoadSeg.Label.Contains(\"Up\");"
    print "                template = isUp ? slopeLeftModule : slopeRightModule;"
    print "            } else {"
    print "                template = GetBestFit(sidewalkModules, segWidth);"
    print "                if (template != null) segWidth = template.moduleConfig.currentTerrainWidth;"
    print "            }"
    print ""
    print "            if (template != null) {"
    print "                SegmentData swSeg = new SegmentData {"
    print "                    Template = template,"
    print "                    X_Position = segX,"
    print "                    Y_Elevation = matchingRoadSeg.Y_Elevation,"
    print "                    Width = segWidth,"
    print "                    Label = isSlope ? \"Sidewalk_Slope\" : \"Sidewalk_Flat\","
    print "                    IsSlope = isSlope,"
    print "                    SpawnObstacles = !isSlope,"
    print "                    RoadElevationAtX = matchingRoadSeg.Y_Elevation,"
    print "                    SidewalkRelativeLevel = 1"
    print "                };"
    print "                blueprint.SidewalkTrack.Segments.Add(swSeg);"
    print "            }"
    print "            currentX += segWidth;"
    print "        }"
    print "    }"
    print ""
    next;
}
/private static void Pass4_FinalizeObstacles/ {
    in_func = 0;
}
!in_func { print }
' Assets/Scripts/Utils/LevelGeneratorEngine.cs > tmp.cs && mv tmp.cs Assets/Scripts/Utils/LevelGeneratorEngine.cs
